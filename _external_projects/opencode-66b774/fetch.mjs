import { makeClient } from './lib.mjs';
import fs from 'fs';
const BASE = 'https://tutorialinjectid.my.id';
const c = makeClient(BASE);
const slug = (process.argv[2] || '/').replace(/[^a-z0-9]+/gi, '_').replace(/^_+/, '').replace(/_+$/, '') || 'root';
const r = await c.get(process.argv[2] || '/');
fs.writeFileSync('/tmp/opencode/f_' + slug + '.html', r.body);
console.log('path:', process.argv[2], 'status:', r.status, 'len:', r.body.length, 'ct:', r.ct, 'challenge?', /wsidchk/.test(r.body));
const title = (r.body.match(/<title[^>]*>([^<]*)<\/title>/i) || [, ''])[1].trim();
console.log('title:', title);
console.log('\n--- FORM ---');
console.log([...r.body.matchAll(/<form[\s\S]*?<\/form>/gi)].map(m => m[0].replace(/\s+/g, ' ').slice(0, 600)).join('\n\n').slice(0, 2500));
console.log('\n--- AJAX / FETCH TARGETS ---');
console.log([...new Set([...r.body.matchAll(/(?:fetch|axios\.(?:get|post)|XMLHttpRequest|url\s*[:=])\s*\(?\s*['"`]([^'"`\n]{2,120})['"`]/gi)].map(m => m[1]))].join('\n').slice(0, 2000));
console.log('\n--- .php / api refs ---');
console.log([...new Set([...r.body.matchAll(/["'(]([^"'()\s]*(?:\.php|\/api\/)[^"'()\s]*)["')]/g)].map(m => m[1]))].join('\n').slice(0, 2000));
console.log('\n--- INLINE SCRIPTS (yang bukan vendor) ---');
const inl = [...r.body.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/gi)].map(m => m[1].trim()).filter(s => s.length > 40 && !s.includes('wsidchk'));
console.log(inl.map(s => s.replace(/\s+/g, ' ')).join('\n;\n').slice(0, 4000));
