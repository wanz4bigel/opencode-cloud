
(function(){
  var loanEl = document.getElementById('loanRange');
  var loanLabel = document.getElementById('loanLabel');
  var monthlyLabel = document.getElementById('monthlyLabel');
  var disbursedLabel = document.getElementById('disbursedLabel');
  var tenorButtons = document.querySelectorAll('.tenor-chip');
  var tenor = 3;

  function formatIDR(n){
    return 'Rp' + Math.round(n).toLocaleString('id-ID');
  }
  function render(){
    var loan = Number(loanEl.value);
    var dailyRate = 0.001;
    var days = tenor * 30;
    var fee = loan * dailyRate * days;
    var monthly = (loan + fee) / tenor;
    var disbursed = loan * 0.95;
    loanLabel.textContent = formatIDR(loan);
    monthlyLabel.textContent = formatIDR(monthly);
    disbursedLabel.textContent = formatIDR(disbursed);
    tenorButtons.forEach(function(btn){
      btn.classList.toggle('selected', Number(btn.dataset.tenor) === tenor);
    });
  }
  loanEl.addEventListener('input', render);
  tenorButtons.forEach(function(btn){
    btn.addEventListener('click', function(){
      tenor = Number(btn.dataset.tenor);
      render();
    });
  });
  render();
})();
